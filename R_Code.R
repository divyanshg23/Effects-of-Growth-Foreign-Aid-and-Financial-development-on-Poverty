 library(kernlab)
 nw_model <- ksvm(dataset$year,dataset$povgap, type = "eps-bsvr", kernel = "rbfdot", kpar = "automatic")
 y_hat<- predict(nw_model, data.frame(x = dataset$year))
 plot(dataset$year,dataset$povgap, pch = 16, col = "blue", main = "Nadaraya-Watson Estimation")
 lines(dataset$year,dataset$povgap, col = "black", lwd = 2)
 lines(dataset$year, y_hat, col = "red", lwd = 2, lty = 2)
 legend("topright", legend = c("Nadaraya", "normal"), col = c("red", "black"), lty = 1)
